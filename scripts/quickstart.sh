#!/bin/sh
# End-to-end local demo: build, init, mock OpenAI, serve, create a virtual key, and
# send one request. Leaves .quickstart/ ready so you can start again without
# regenerating secrets.
set -eu
cd "$(dirname "$0")/.."

QS="${KEMAN_QUICKSTART_DIR:-.quickstart}"
PROXY_PORT="${KEMAN_QUICKSTART_PROXY_PORT:-8080}"
ADMIN_PORT="${KEMAN_QUICKSTART_ADMIN_PORT:-8081}"

for port in "$PROXY_PORT" "$ADMIN_PORT"; do
  if curl -s -o /dev/null --max-time 1 "http://127.0.0.1:$port/"; then
    echo "something is already listening on 127.0.0.1:$port (another keman?)." >&2
    echo "stop it, or set KEMAN_QUICKSTART_PROXY_PORT / KEMAN_QUICKSTART_ADMIN_PORT." >&2
    exit 1
  fi
done
mkdir -p "$QS"

if [ ! -f "$QS/master.key" ]; then
  openssl rand -base64 32 > "$QS/master.key"
  chmod 600 "$QS/master.key"
fi

if [ ! -f "$QS/keman.yaml" ]; then
  cat > "$QS/keman.yaml" <<EOF
# Generated by scripts/quickstart.sh. Keys live in the database.
proxy_listen: 127.0.0.1:$PROXY_PORT
admin_listen: 127.0.0.1:$ADMIN_PORT
database: $QS/keman.db
master_key_file: $QS/master.key
trusted_proxies: []
EOF
  chmod 600 "$QS/keman.yaml"
fi

CGO_ENABLED=0 go build -o "$QS/keman" ./cmd/keman
CGO_ENABLED=0 go build -o "$QS/mock-openai" ./examples/mock-openai

if [ ! -f "$QS/keman.db" ]; then
  "$QS/keman" --config "$QS/keman.yaml" init | tee "$QS/init.out"
fi

if [ ! -f "$QS/admin.token" ]; then
  awk '/^admin_token: / { print $2 }' "$QS/init.out" > "$QS/admin.token"
  chmod 600 "$QS/admin.token"
fi
ADMIN_TOKEN="$(cat "$QS/admin.token")"
if [ -z "$ADMIN_TOKEN" ]; then
  echo "could not read admin token from $QS/init.out" >&2
  exit 1
fi

MOCK_LISTEN="${KEMAN_MOCK_LISTEN:-127.0.0.1:18080}"
LISTEN="$MOCK_LISTEN" "$QS/mock-openai" >"$QS/mock.log" 2>&1 &
MOCK_PID=$!

"$QS/keman" --config "$QS/keman.yaml" serve >"$QS/serve.log" 2>&1 &
SERVE_PID=$!

cleanup() {
  kill "$SERVE_PID" "$MOCK_PID" >/dev/null 2>&1 || true
  wait "$SERVE_PID" "$MOCK_PID" 2>/dev/null || true
}
trap cleanup EXIT INT TERM

ready=0
i=0
while [ "$i" -lt 80 ]; do
  code="$(curl -s -o /dev/null -w '%{http_code}' http://127.0.0.1:$ADMIN_PORT/metrics || true)"
  mock="$(curl -s -o /dev/null -w '%{http_code}' "http://$MOCK_LISTEN/v1/models" || true)"
  if ! kill -0 "$SERVE_PID" 2>/dev/null; then
    break
  fi
  if [ "$code" = "401" ] && [ "$mock" = "200" ]; then
    ready=1
    break
  fi
  i=$((i + 1))
  sleep 0.1
done
if [ "$ready" != 1 ]; then
  echo "keman serve or the mock upstream did not start; logs:" >&2
  echo "-- serve --" >&2
  tail -n 40 "$QS/serve.log" >&2
  echo "-- mock --" >&2
  tail -n 40 "$QS/mock.log" >&2
  exit 1
fi

KEMAN="$QS/keman"
CFG="$QS/keman.yaml"
export KEMAN_ADMIN_TOKEN="$ADMIN_TOKEN"

if [ ! -f "$QS/key.json" ]; then
  MOCK_HOST="${MOCK_LISTEN%:*}"
  MOCK_PORT="${MOCK_LISTEN##*:}"
  "$KEMAN" --config "$CFG" upstream add --name openai --profile openai --host "$MOCK_HOST" --port "$MOCK_PORT" >"$QS/upstream.json"
  printf 'sk-mock-quickstart\n' > "$QS/upstream.key"
  chmod 600 "$QS/upstream.key"
  "$KEMAN" --config "$CFG" credential add --upstream openai --name primary --header "Authorization: Bearer {key}" --secret-file "$QS/upstream.key" >"$QS/credential.json"
  "$KEMAN" --config "$CFG" key create --credential primary --name laptop >"$QS/key.json"
fi

VIRTUAL_KEY="$(awk -F'"' '/"token":/ { print $4; exit }' "$QS/key.json")"
if [ -z "$VIRTUAL_KEY" ]; then
  echo "key create did not print a token; see $QS/key.json" >&2
  exit 1
fi
printf '%s\n' "$VIRTUAL_KEY" > "$QS/virtual.key"
chmod 600 "$QS/virtual.key"

BODY="$(curl -sS http://127.0.0.1:$PROXY_PORT/v1/chat/completions \
  -H "Authorization: Bearer $VIRTUAL_KEY" \
  -H "Content-Type: application/json" \
  -d '{"model":"gpt-4o-mini","messages":[{"role":"user","content":"hi"}]}')"
echo "$BODY" | tee "$QS/sample.json" >/dev/null
echo "$BODY" | grep -q '"hello"' || {
  echo "sample request failed: $BODY" >&2
  echo "serve log:" >&2
  tail -n 40 "$QS/serve.log" >&2
  exit 1
}

echo
echo "Firing a detection through the proxy (five blocked requests)..."
"$KEMAN" --config "$CFG" detection test --live --secret-file "$QS/virtual.key"

echo
echo "Quickstart succeeded."
echo "  proxy:        http://127.0.0.1:$PROXY_PORT"
echo "  admin:        http://127.0.0.1:$ADMIN_PORT"
echo "  virtual key:  $QS/virtual.key  (shown once in $QS/key.json)"
echo "  admin token:  $QS/admin.token"
echo
echo "Official OpenAI SDKs need the /v1 suffix:"
echo "  export KEMAN_KEY=\"\$(cat $QS/virtual.key)\""
echo "  python3 examples/sdk_stream.py"
echo "  node examples/sdk_stream.mjs"
echo
echo "The laptop key now has an allowlist detection in $QS/keman.db."
echo "List it after the server is up:"
echo "  KEMAN_ADMIN_TOKEN=\"\$(cat $QS/admin.token)\" $QS/keman --config $QS/keman.yaml detection list"
echo
echo "Open the terminal UI on this install (it starts the server and stops it on exit):"
echo "  KEMAN_ADMIN_TOKEN=\"\$(cat $QS/admin.token)\" $QS/keman --config $QS/keman.yaml"
echo "Or keep a server running on its own:"
echo "  $QS/keman --config $QS/keman.yaml serve"
echo
echo "This script stops the demo processes on exit. Start the mock with:"
echo "  LISTEN=$MOCK_LISTEN $QS/mock-openai"

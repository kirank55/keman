#!/bin/sh
# Seed a demo install in .demo/ with a small team's keys, a week of normal use
# compressed into a minute, and the incidents Keman is built to catch: a
# stolen key used from a new country, a locked key tried from outside its
# network, a disabled key in use, a provider key revoked upstream, a decoy
# that fired, and blocked attempts to reach endpoints a key may not call.
#
# Nothing leaves this machine. The upstream is a local mock, alerts go to a
# local sink (.demo/alerts.jsonl), and every address and ASN is from a
# documentation range. Run it again to start over.
#
#   ./scripts/demo.sh             seed, stop, and print the command to open the UI
#   KEMAN_DEMO_KEEP=1 ./scripts/demo.sh   seed and keep the server running
set -eu
cd "$(dirname "$0")/.."

D="${KEMAN_DEMO_DIR:-.demo}"
PROXY_PORT="${KEMAN_DEMO_PROXY_PORT:-8080}"
ADMIN_PORT="${KEMAN_DEMO_ADMIN_PORT:-8081}"
UP="${KEMAN_DEMO_UPSTREAM:-127.0.0.1:18090}"
SINK="${KEMAN_DEMO_SINK:-127.0.0.1:18091}"
PROXY="http://127.0.0.1:$PROXY_PORT"

for port in "$PROXY_PORT" "$ADMIN_PORT" "${UP##*:}" "${SINK##*:}"; do
  if curl -s -o /dev/null --max-time 1 "http://127.0.0.1:$port/"; then
    echo "something is already listening on 127.0.0.1:$port." >&2
    echo "stop it, or set KEMAN_DEMO_PROXY_PORT, KEMAN_DEMO_ADMIN_PORT, KEMAN_DEMO_UPSTREAM or KEMAN_DEMO_SINK." >&2
    exit 1
  fi
done

rm -rf "$D"
mkdir -p "$D/keys"
chmod 700 "$D"

echo "building"
CGO_ENABLED=0 go build -o "$D/keman" ./cmd/keman
CGO_ENABLED=0 go build -o "$D/demo" ./examples/demo
"$D/demo" geoip "$D/geoip"

cat > "$D/keman.yaml" <<EOF
# Generated by scripts/demo.sh.
proxy_listen: 127.0.0.1:$PROXY_PORT
admin_listen: 127.0.0.1:$ADMIN_PORT
database: $D/keman.db
# The demo traffic generator sends X-Forwarded-For from localhost.
trusted_proxies: [127.0.0.1/32]
geoip_country_db: $D/geoip/country.mmdb
geoip_asn_db: $D/geoip/asn.mmdb
EOF

"$D/keman" --config "$D/keman.yaml" init > "$D/init.out"
awk '/^admin_token: / { print $2 }' "$D/init.out" > "$D/admin.token"
chmod 600 "$D/admin.token"
KEMAN_ADMIN_TOKEN="$(cat "$D/admin.token")"
export KEMAN_ADMIN_TOKEN
[ -n "$KEMAN_ADMIN_TOKEN" ] || { echo "init did not print an admin token" >&2; exit 1; }

"$D/demo" upstream "$UP" > "$D/upstream.log" 2>&1 &
UP_PID=$!
"$D/demo" sink "$SINK" "$D/alerts.jsonl" > "$D/sink.log" 2>&1 &
SINK_PID=$!
SERVE_PID=
start_server() {
  "$D/keman" --config "$D/keman.yaml" serve >> "$D/serve.log" 2>&1 &
  SERVE_PID=$!
  i=0
  until [ "$(curl -s -o /dev/null -w '%{http_code}' "http://127.0.0.1:$ADMIN_PORT/metrics")" = 401 ]; do
    i=$((i + 1))
    if [ "$i" -gt 100 ] || ! kill -0 "$SERVE_PID" 2>/dev/null; then
      echo "keman serve did not start:" >&2
      tail -n 40 "$D/serve.log" >&2
      exit 1
    fi
    sleep 0.1
  done
}
stop_server() {
  kill "$SERVE_PID" 2>/dev/null || true
  wait "$SERVE_PID" 2>/dev/null || true
  SERVE_PID=
}

cleanup() {
  kill $SERVE_PID "$UP_PID" "$SINK_PID" >/dev/null 2>&1 || true
  wait $SERVE_PID "$UP_PID" "$SINK_PID" 2>/dev/null || true
}
trap cleanup EXIT INT TERM
start_server

k() { "$D/keman" --config "$D/keman.yaml" "$@"; }
quiet() { k "$@" > /dev/null; }
token() { sed -n 's/.*"token": *"\([^"]*\)".*/\1/p' | head -n 1; }
newkey() { # newkey NAME CREDENTIAL [key create flags...]
  name="$1"
  cred="$2"
  shift 2
  k key create --credential "$cred" --name "$name" "$@" 2>> "$D/cli.log" | token > "$D/keys/$name"
  [ -s "$D/keys/$name" ] || { echo "key create $name failed" >&2; exit 1; }
}
send() { # send KEY IP [traffic flags...]
  key="$1"
  ip="$2"
  shift 2
  "$D/demo" traffic -proxy "$PROXY" -key-file "$D/keys/$key" -ip "$ip" "$@"
}
name_client() {
  curl -fsS -o /dev/null -X PUT "http://127.0.0.1:$ADMIN_PORT/v1/clients" \
    -H "Authorization: Bearer $KEMAN_ADMIN_TOKEN" -H "Content-Type: application/json" \
    -d "{\"ip\":\"$1\",\"name\":\"$2\"}"
}

echo "setting up upstreams, credentials and alerts"
UP_HOST="${UP%:*}"
UP_PORT="${UP##*:}"
quiet upstream add --name openai --profile openai --host "$UP_HOST" --port "$UP_PORT"
quiet upstream add --name anthropic --profile anthropic --host "$UP_HOST" --port "$UP_PORT"
quiet upstream add --name stripe --profile generic --host "$UP_HOST" --port "$UP_PORT" \
  --path "POST /v1/charges" --path "GET /v1/customers/*"

printf 'sk-proj-demo-openai-main\n' > "$D/openai.secret"
printf 'sk-proj-demo-revoked-at-provider\n' > "$D/openai-staging.secret"
printf 'sk-ant-demo-anthropic-main\n' > "$D/anthropic.secret"
printf 'sk_live_demo_stripe\n' > "$D/stripe.secret"
printf 'demo-webhook-signing-secret\n' > "$D/webhook.secret"
chmod 600 "$D"/*.secret
quiet credential add --upstream openai --name openai-main --header "Authorization: Bearer {key}" --secret-file "$D/openai.secret"
quiet credential add --upstream openai --name openai-staging --header "Authorization: Bearer {key}" --secret-file "$D/openai-staging.secret"
quiet credential add --upstream anthropic --name anthropic-main --header "x-api-key: {key}" --secret-file "$D/anthropic.secret"
quiet credential add --upstream stripe --name stripe-live --header "Authorization: Bearer {key}" --secret-file "$D/stripe.secret"
quiet alert add --kind slack --url "http://$SINK/slack"
quiet alert add --kind webhook --url "http://$SINK/webhook" --secret-file "$D/webhook.secret"

echo "creating virtual keys"
newkey laptop openai-main --expires 30d
newkey ci-github anthropic-main --expires 30d
newkey prod-api openai-main --expires 90d
newkey support-bot anthropic-main --expires never
newkey billing-svc stripe-live --expires 90d
newkey staging-worker openai-staging
newkey old-intern openai-main
k canary create --credential openai-main --name repo-decoy --base-url "$PROXY" > "$D/repo-decoy.env" 2>> "$D/cli.log"
sed -n 's/^OPENAI_API_KEY=//p' "$D/repo-decoy.env" > "$D/keys/repo-decoy"

echo "locking keys down"
quiet policy set laptop --cidr 203.0.113.0/25 --rpm 60
quiet policy set ci-github --cidr 198.51.100.0/25 --rpm 120 --daily-usd 8 --monthly-usd 150
quiet policy set prod-api --cidr 192.0.2.0/25 --country DE --rpm 1200 --daily-usd 40 --monthly-usd 800 \
  --model gpt-4o --model gpt-4o-mini
quiet policy set billing-svc --cidr 192.0.2.0/25

name_client 203.0.113.10 dev-laptop
name_client 203.0.113.11 office-mac
name_client 198.51.100.7 github-actions
name_client 192.0.2.20 prod-eu-1
name_client 192.0.2.21 prod-eu-2
name_client 192.0.2.30 billing-eu
name_client 192.0.2.40 staging

echo "backfilling a week of normal use"
stop_server
"$D/demo" history -db "$D/keman.db" -geoip "$D/geoip" -days 8
start_server

echo "today"
send prod-api 192.0.2.20 -n 14 -model gpt-4o-mini
send support-bot 192.0.2.20 -n 6 -profile anthropic -model claude-haiku-4-5
send ci-github 198.51.100.7 -n 9 -profile anthropic -model claude-sonnet-4-5
send billing-svc 192.0.2.30 -n 4 -profile generic
# Planned rotation: the old laptop key keeps working for a day.
k key rotate laptop --grace 24h 2>> "$D/cli.log" | token > "$D/keys/laptop"
send laptop 203.0.113.10 -n 5 -model gpt-4o-mini
quiet key disable old-intern

echo "incidents"
# support-bot is open to every address and never expires. A copy of it
# drains the key with long Opus calls from a new country, then a second one.
send support-bot 203.0.113.200 -n 18 -profile anthropic -model claude-opus-4-5 -max-tokens 16000 -c 4
send support-bot 192.0.2.200 -n 3 -profile anthropic -model claude-opus-4-5
# A copy of prod-api tried from outside its network and country.
send prod-api 203.0.113.200 -n 6 -model gpt-4o
# billing-svc probed for endpoints it may not call, including a ../ escape.
send billing-svc 192.0.2.30 -n 3 -profile generic -method GET -path /v1/payouts
send billing-svc 192.0.2.30 -n 2 -profile generic -method POST -path /v1/transfers
send billing-svc 192.0.2.30 -n 2 -profile generic -method GET -path /v1/customers/../balance
# A disabled key still in use.
send old-intern 198.51.100.200 -n 4 -model gpt-4o
# The staging provider key was rotated at OpenAI; every call now fails.
send staging-worker 192.0.2.40 -n 12 -model gpt-4o-mini
# Someone found the decoy planted in .env.
send repo-decoy 192.0.2.200 -n 1 -model gpt-4o

echo "waiting for detections"
i=0
while :; do
  n="$(k detection list 2>/dev/null | grep -c '"rule"' || true)"
  if [ "$n" -ge 20 ] || [ "$i" -gt 50 ]; then
    break
  fi
  i=$((i + 1))
  sleep 0.2
done
sleep 1
echo "  $n detections, $(wc -l < "$D/alerts.jsonl" 2>/dev/null || echo 0) alert deliveries in $D/alerts.jsonl"

echo
echo "Demo ready in $D/."
echo "Open the terminal UI:"
echo "  KEMAN_ADMIN_TOKEN=\"\$(cat $D/admin.token)\" $D/keman --config $D/keman.yaml"
echo "Or try the CLI:"
echo "  KEMAN_ADMIN_TOKEN=\"\$(cat $D/admin.token)\" $D/keman --config $D/keman.yaml exposure"

if [ "${KEMAN_DEMO_KEEP:-}" = 1 ]; then
  echo
  echo "Server, mock upstream and alert sink are running. Ctrl+C stops them."
  echo "  proxy $PROXY   virtual keys in $D/keys/"
  wait "$SERVE_PID"
fi
